class TestCaseFoldCollision(unittest.TestCase):
    def test_file_name_case_collision(self):
        self.assertIn(pathscan.R_CASE, rules_fired(["a/B.txt", "a/b.txt"]))

    def test_directory_component_case_collision(self):
        self.assertIn(pathscan.R_CASE, rules_fired(["A/x.txt", "a/x.txt"]))

    def test_distinct_names_do_not_collide(self):
        self.assertNotIn(pathscan.R_CASE, rules_fired(["a.txt", "b.txt"]))

    def test_members_are_sorted_and_complete(self):
        f = [x for x in scan_paths(["b.TXT", "B.txt", "b.txt"])["findings"]
             if x["rule_id"] == pathscan.R_CASE]
        self.assertEqual(len(f), 1)
        self.assertEqual(f[0]["paths"], ["B.txt", "b.TXT", "b.txt"])

    def test_pure_normalisation_pair_is_not_reported_as_case(self):
        # One defect, one rule: NFC vs NFD of the same name is a
        # normalisation collision, not a case collision.
        fired = rules_fired(["caf\u00e9.txt", "cafe\u0301.txt"])
        self.assertIn(pathscan.R_NORM, fired)
        self.assertNotIn(pathscan.R_CASE, fired)

    def test_case_and_normalisation_together_reported_as_case(self):
        fired = rules_fired(["CAF\u00c9.txt", "cafe\u0301.txt"])
        self.assertIn(pathscan.R_CASE, fired)

    def test_turkish_dotless_i_folds_together(self):
        # casefold() maps both to "i"-ish forms; documenting real behaviour.
        report = scan_paths(["I.txt", "i.txt"])
        self.assertEqual(report["summary"][pathscan.R_CASE], 1)


