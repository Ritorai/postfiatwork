class TestStdlibOnlyImports(unittest.TestCase):
    ALLOWED = {"argparse", "json", "os", "re", "subprocess", "sys", "unicodedata"}

    def test_pathscan_imports_only_the_allow_list(self):
        import ast
        with open(PATHSCAN_PY, encoding="utf-8") as fh:
            tree = ast.parse(fh.read())
        found = set()
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                found.update(a.name.split(".")[0] for a in node.names)
            elif isinstance(node, ast.ImportFrom) and node.module:
                found.add(node.module.split(".")[0])
        self.assertEqual(found - self.ALLOWED, set(), "unexpected imports: %s" % (found - self.ALLOWED))


