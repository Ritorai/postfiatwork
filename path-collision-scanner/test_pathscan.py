#!/usr/bin/env python3
"""Test suite for pathscan.py. Stdlib-only (unittest, tempfile, subprocess,
json, os, sys, hashlib).

Every scenario is a path *list*, never a directory tree, because several of
the names under test cannot exist as files on the machine running the
tests -- that is the whole point of the tool. The `fixtures/` tree is
generated by make_fixtures.py and built on demand by setUpModule().
"""

import hashlib
import json
import os
import shutil
import subprocess
import sys
import tempfile
import unittest

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import pathscan  # noqa: E402
import make_fixtures  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
PATHSCAN_PY = os.path.join(HERE, "pathscan.py")
MAKE_FIXTURES_PY = os.path.join(HERE, "make_fixtures.py")
FIXTURES_DIR = os.path.join(HERE, "fixtures")
PY = sys.executable or "python3"

HAVE_GIT = shutil.which("git") is not None
NEEDS_GIT = unittest.skipUnless(HAVE_GIT, "git is not on PATH")


def setUpModule():
    """fixtures/ is generated, not committed (repo convention)."""
    if not os.path.isdir(FIXTURES_DIR):
        make_fixtures.build(FIXTURES_DIR)


def run_cli(args, cwd=None, stdin_bytes=None):
    proc = subprocess.run(
        [PY, PATHSCAN_PY] + args,
        cwd=cwd,
        input=stdin_bytes,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        timeout=120,
    )
    return proc.returncode, proc.stdout.decode("utf-8"), proc.stderr.decode("utf-8")


def write_list(dirpath, name, paths, trailing_nul=True):
    data = b"\0".join(p.encode("utf-8") for p in paths)
    if paths and trailing_nul:
        data += b"\0"
    full = os.path.join(dirpath, name)
    with open(full, "wb") as fh:
        fh.write(data)
    return full


def scan_paths(paths):
    """Run the scanner in-process over a list and return the report dict."""
    return pathscan.build_report(paths, "path-list", set(pathscan.ALL_RULES))


def rules_fired(paths):
    return sorted({f["rule_id"] for f in scan_paths(paths)["findings"]})


class TempMixin:
    def tmp(self):
        td = tempfile.TemporaryDirectory()
        self.addCleanup(td.cleanup)
        return td.name


