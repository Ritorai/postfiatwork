class TestCanonicalJson(unittest.TestCase):
    def test_single_trailing_newline(self):
        out = pathscan.canonical_json({"a": 1})
        self.assertTrue(out.endswith("\n"))
        self.assertFalse(out.endswith("\n\n"))

    def test_sorted_keys_tight_separators(self):
        self.assertEqual(pathscan.canonical_json({"b": 1, "a": 2}), '{"a":2,"b":1}\n')

    def test_ascii_only(self):
        out = pathscan.canonical_json({"p": "caf\u00e9"})
        self.assertIn("\\u00e9", out)
        self.assertTrue(all(ord(c) < 128 for c in out))

    def test_newline_in_value_is_escaped_not_literal(self):
        out = pathscan.canonical_json({"p": "a\nb"})
        self.assertIn("\\n", out)
        self.assertEqual(out.count("\n"), 1)

    def test_deterministic(self):
        obj = {"z": [3, 1, 2], "a": {"y": 1, "x": 2}}
        self.assertEqual(pathscan.canonical_json(obj), pathscan.canonical_json(obj))


