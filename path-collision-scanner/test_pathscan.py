class TestReportShape(unittest.TestCase):
    def test_clean_report_status_and_counts(self):
        r = scan_paths(["a.txt", "b/c.md"])
        self.assertEqual(r["status"], "clean")
        self.assertEqual(r["paths_scanned"], 2)
        self.assertEqual(r["distinct_paths"], 2)
        self.assertEqual(r["findings"], [])

    def test_summary_covers_every_rule_even_at_zero(self):
        r = scan_paths(["a.txt"])
        self.assertEqual(set(r["summary"]), set(pathscan.ALL_RULES))

    def test_summary_matches_finding_counts(self):
        r = scan_paths(["A.txt", "a.txt", "aux", "bad?.md"])
        counted = {}
        for f in r["findings"]:
            counted[f["rule_id"]] = counted.get(f["rule_id"], 0) + 1
        for rule, n in r["summary"].items():
            self.assertEqual(n, counted.get(rule, 0), rule)

    def test_schema_version_and_tool_name(self):
        r = scan_paths([])
        self.assertEqual(r["schema_version"], pathscan.SCHEMA_VERSION)
        self.assertEqual(r["tool"], "path-collision-scanner")

    def test_findings_sorted_by_rule_then_paths(self):
        r = scan_paths(["z.txt", "Z.txt", "aux", "b?.md", "c\nd.txt"])
        keys = [(f["rule_id"], f["paths"]) for f in r["findings"]]
        self.assertEqual(keys, sorted(keys))

    def test_input_order_does_not_change_the_report(self):
        a = ["Z.txt", "z.txt", "aux", "b?.md"]
        b = ["b?.md", "aux", "z.txt", "Z.txt"]
        self.assertEqual(pathscan.canonical_json(scan_paths(a)),
                         pathscan.canonical_json(scan_paths(b)))

    def test_empty_input_is_clean(self):
        r = scan_paths([])
        self.assertEqual(r["status"], "clean")
        self.assertEqual(r["paths_scanned"], 0)


