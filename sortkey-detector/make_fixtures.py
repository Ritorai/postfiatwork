def write_tree(tree_name, dest_root):
    spec = TREES[tree_name]
    target = os.path.join(dest_root, tree_name)
    if os.path.exists(target):
        # Scoped: only ever removes the exact directory this script is
        # about to recreate, never an ancestor or an unrelated path.
        shutil.rmtree(target)
    os.makedirs(target, exist_ok=True)

    for rel_dir in spec["empty_dirs"]:
        os.makedirs(os.path.join(target, rel_dir), exist_ok=True)

    for rel_path, b64_parts in spec["files"]:
        full = os.path.join(target, rel_path)
        parent = os.path.dirname(full)
        if parent:
            os.makedirs(parent, exist_ok=True)
        data = base64.b64decode("".join(b64_parts))
        with open(full, "wb") as fh:
            fh.write(data)

    return len(spec["files"]), len(spec["empty_dirs"])


def main(argv=None):
    parser = argparse.ArgumentParser(prog="make_fixtures.py")
    parser.add_argument("--out", default=".", help="directory under which to (re)create "
                         "fixtures/, controls/ and toy_tool/ (default: current directory)")
    args = parser.parse_args(argv)

    dest_root = args.out
    os.makedirs(dest_root, exist_ok=True)

    total_files = 0
    total_empty_dirs = 0
    for tree_name in sorted(TREES):
        nf, ne = write_tree(tree_name, dest_root)
        total_files += nf
        total_empty_dirs += ne
        print("make_fixtures: wrote %s/%s (%d files, %d empty dirs)" % (dest_root, tree_name, nf, ne))

    print("make_fixtures: done (%d files, %d empty dirs total)" % (total_files, total_empty_dirs))
    return 0


if __name__ == "__main__":
    sys.exit(main())
