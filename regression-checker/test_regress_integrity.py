class TestFixtureGenerator(unittest.TestCase):
    def test_on_disk_fixtures_match_the_generator(self):
        proc = subprocess.run([PY, MAKE_FIXTURES_PY, "--check"], cwd=HERE,
                              stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=120)
        self.assertEqual(proc.returncode, 0, msg=proc.stdout.decode() + proc.stderr.decode())

    def test_generator_is_deterministic_across_two_runs(self):
        with tempfile.TemporaryDirectory() as td:
            a, b = os.path.join(td, "a"), os.path.join(td, "b")
            make_fixtures.build(a)
            make_fixtures.build(b)
            self.assertEqual(make_fixtures.snapshot(a), make_fixtures.snapshot(b))

    def test_generated_tree_has_the_seven_documented_tool_dirs(self):
        with tempfile.TemporaryDirectory() as td:
            out = os.path.join(td, "fixtures")
            make_fixtures.build(out)
            dirs = sorted(d for d in os.listdir(out) if os.path.isdir(os.path.join(out, d)))
        self.assertEqual(dirs, sorted(make_fixtures.FIXTURE_TOOLS))
        self.assertEqual(len(dirs), 7)

    def test_tool_error_has_no_tool_py(self):
        self.assertFalse(os.path.exists(os.path.join(FIXTURES_DIR, "tool_error", "tool.py")))

    def test_ok_baseline_has_exactly_two_unbaselineable(self):
        data = read_json(os.path.join(FIXTURES_DIR, "baselines_ok.json"))
        n = sum(1 for e in data["tools"].values() if e.get("status") == "unbaselineable")
        self.assertEqual(n, 2)

    def test_drift_baseline_names_ghost_tool_with_no_directory(self):
        data = read_json(os.path.join(FIXTURES_DIR, "baselines_drift.json"))
        self.assertIn("ghost_tool", data["tools"])
        self.assertFalse(os.path.exists(os.path.join(FIXTURES_DIR, "ghost_tool")))

    def test_no_absolute_interpreter_path_in_generated_baselines(self):
        # An absolute sys.executable baked into a baseline file is
        # unreproducible on any other machine.
        for name in ("baselines_ok.json", "baselines_drift.json"):
            text = read_text(os.path.join(FIXTURES_DIR, name))
            self.assertNotIn("/usr/", text, name)
            self.assertNotIn("/home", text, name)
            self.assertNotIn(HERE, text, name)

    def test_no_boolean_exit_codes_in_generated_baselines(self):
        for name in ("baselines_ok.json", "baselines_drift.json"):
            data = read_json(os.path.join(FIXTURES_DIR, name))
            for tool, entry in data["tools"].items():
                if entry.get("status") == "unbaselineable":
                    continue
                self.assertTrue(regress.is_exit_code(entry["expected_exit_code"]),
                                "%s/%s" % (name, tool))

    def test_shell_meta_token_survives_verbatim(self):
        # Proof that regress.py never routes a command through a shell.
        code, out, err = run_cli(
            ["--root", "fixtures", "--baselines", "fixtures/baselines_ok.json"], cwd=HERE)
        self.assertEqual(code, 0, msg=err)
        report = json.loads(out)
        by_name = {r["tool"]: r for r in report["results"]}
        self.assertEqual(by_name["tool_shell_meta"]["status"], "clean")


if __name__ == "__main__":
    unittest.main()
