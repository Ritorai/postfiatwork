# 2. A crashed run is not a result
# ---------------------------------------------------------------------------

class TestTerminationRecorded(TempRootMixin, unittest.TestCase):
    def file_entry(self, exit_code=0, digest=None):
        return {
            "status": "baselined",
            "command": ["python3", "tool.py", "-o", "{REPORT}"],
            "report_mode": "file",
            "expected_exit_code": exit_code,
            "expected_report_sha256": digest,
        }

    def test_normal_run_reports_exited(self):
        root = self.make_root()
        d = self.make_tool(root, "t1", GOOD_REPORT)
        result = regress.run_tool(d, self.file_entry(), timeout=60)
        self.assertTrue(result["ok"])
        self.assertEqual(result["termination"], regress.TERM_EXITED)
        self.assertIsNone(result["signal"])

    @POSIX_ONLY
    def test_signalled_run_reports_signalled_and_signal_number(self):
        root = self.make_root()
        d = self.make_tool(root, "t1", PARTIAL_THEN_KILL)
        result = regress.run_tool(d, self.file_entry(), timeout=60)
        self.assertEqual(result["termination"], regress.TERM_SIGNALLED)
        self.assertEqual(result["signal"], 9)

    @POSIX_ONLY
    def test_partial_report_is_still_read_but_flagged(self):
        # The bytes are readable -- that was never the problem. The problem
        # was that nothing recorded HOW the process ended.
        root = self.make_root()
        d = self.make_tool(root, "t1", PARTIAL_THEN_KILL)
        result = regress.run_tool(d, self.file_entry(), timeout=60)
        self.assertTrue(result["ok"])
        self.assertGreater(result["report_bytes_length"], 0)
        self.assertEqual(result["termination"], regress.TERM_SIGNALLED)


class TestAbnormalTerminationDrift(TempRootMixin, unittest.TestCase):
    def run_report(self, root, baselines):
        path = write_baselines(root, baselines)
        code, out, err = run_cli(["--root", root, "--baselines", path])
        return code, json.loads(out), err

    def entry(self, exit_code, digest):
        return {
            "command": ["python3", "tool.py", "-o", "{REPORT}"],
            "report_mode": "file",
            "expected_exit_code": exit_code,
            "expected_report_sha256": digest,
        }

    @POSIX_ONLY
    def test_signalled_run_raises_abnormal_termination(self):
        root = self.make_root()
        self.make_tool(root, "crasher", PARTIAL_THEN_KILL)
        digest = hashlib.sha256(b'{"tool":"crasher","partial":tr').hexdigest()
        code, report, _ = self.run_report(root, {"crasher": self.entry(-9, digest)})
        result = report["results"][0]
        self.assertIn(regress.DRIFT_ABNORMAL, result["drift_codes"])
        self.assertEqual(code, 1)

    @POSIX_ONLY
    def test_baseline_recording_negative_code_cannot_bless_a_crash(self):
        # The whole point: a baseline that says "-9 is expected" must not
        # make a SIGKILLed run come out clean.
        root = self.make_root()
        self.make_tool(root, "crasher", PARTIAL_THEN_KILL)
        digest = hashlib.sha256(b'{"tool":"crasher","partial":tr').hexdigest()
        _, report, _ = self.run_report(root, {"crasher": self.entry(-9, digest)})
        self.assertEqual(report["results"][0]["status"], "drift")

    @POSIX_ONLY
    def test_detail_carries_termination_and_signal(self):
        root = self.make_root()
        self.make_tool(root, "crasher", PARTIAL_THEN_KILL)
        _, report, _ = self.run_report(root, {"crasher": self.entry(0, None)})
        detail = report["results"][0]["detail"]
        self.assertEqual(detail["termination"], regress.TERM_SIGNALLED)
        self.assertEqual(detail["signal"], 9)

    def test_clean_run_detail_says_exited(self):
        root = self.make_root()
        self.make_tool(root, "t1", GOOD_REPORT)
        digest = hashlib.sha256(b'{"tool":"good"}\n').hexdigest()
        code, report, _ = self.run_report(root, {"t1": self.entry(0, digest)})
        self.assertEqual(code, 0)
        self.assertEqual(report["results"][0]["detail"]["termination"], regress.TERM_EXITED)
        self.assertNotIn("signal", report["results"][0]["detail"])

    def test_abnormal_code_is_in_all_drift_codes(self):
        self.assertIn(regress.DRIFT_ABNORMAL, regress.ALL_DRIFT_CODES)

    def test_drift_counts_include_abnormal_key(self):
        root = self.make_root()
        self.make_tool(root, "t1", GOOD_REPORT)
        digest = hashlib.sha256(b'{"tool":"good"}\n').hexdigest()
        _, report, _ = self.run_report(root, {"t1": self.entry(0, digest)})
        self.assertIn(regress.DRIFT_ABNORMAL, report["drift_counts"])

    def test_schema_version_bumped(self):
        self.assertEqual(regress.SCHEMA_VERSION, 2)


class TestUpdateBaselinesRefusesBadRuns(TempRootMixin, unittest.TestCase):
    def entry(self):
        return {
            "command": ["python3", "tool.py", "-o", "{REPORT}"],
            "report_mode": "file",
            "expected_exit_code": 0,
            "expected_report_sha256": "0" * 64,
        }

    @POSIX_ONLY
    def test_refuses_to_baseline_a_signalled_run(self):
        root = self.make_root()
        self.make_tool(root, "crasher", PARTIAL_THEN_KILL)
        path = write_baselines(root, {"crasher": self.entry()})
        before = read_text(path)
        code, _, err = run_cli(["--update-baselines", "--root", root, "--baselines", path])
        self.assertEqual(code, 2)
        self.assertIn("signal", err)
        self.assertEqual(json.loads(before)["tools"]["crasher"]["expected_report_sha256"],
                         read_json(path)["tools"]["crasher"]["expected_report_sha256"])

    def test_refuses_to_baseline_an_empty_report(self):
        root = self.make_root()
        self.make_tool(root, "empty", EMPTY_REPORT)
        path = write_baselines(root, {"empty": self.entry()})
        code, _, err = run_cli(["--update-baselines", "--root", root, "--baselines", path])
        self.assertEqual(code, 2)
        self.assertIn("0-byte", err)
        self.assertEqual(read_json(path)["tools"]["empty"]["expected_report_sha256"], "0" * 64)

    def test_allow_empty_report_opts_back_in(self):
        root = self.make_root()
        self.make_tool(root, "empty", EMPTY_REPORT)
        path = write_baselines(root, {"empty": self.entry()})
        code, _, err = run_cli(["--update-baselines", "--allow-empty-report",
                                "--root", root, "--baselines", path])
        self.assertEqual(code, 0, msg=err)
        self.assertEqual(read_json(path)["tools"]["empty"]["expected_report_sha256"],
                         hashlib.sha256(b"").hexdigest())

    def test_healthy_run_still_updates(self):
        root = self.make_root()
        self.make_tool(root, "t1", GOOD_REPORT)
        path = write_baselines(root, {"t1": self.entry()})
        code, _, err = run_cli(["--update-baselines", "--root", root, "--baselines", path])
        self.assertEqual(code, 0, msg=err)
        self.assertEqual(read_json(path)["tools"]["t1"]["expected_report_sha256"],
                         hashlib.sha256(b'{"tool":"good"}\n').hexdigest())

    def test_empty_sha256_constant_matches_hashlib(self):
        self.assertEqual(regress.EMPTY_SHA256, hashlib.sha256(b"").hexdigest())


