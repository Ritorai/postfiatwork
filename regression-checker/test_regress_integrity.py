#!/usr/bin/env python3
"""Tests for the two report/exit-code integrity defects in regress.py, and
for the fixtures/ generator that makes the committed CLI tests runnable.

Kept in its own file (same pattern as test_regress_newline.py) so the
original suite stays a readable record of the pre-fix contract.

Three groups:

  1. `expected_exit_code` must reject JSON booleans. `bool` subclasses
     `int` in Python, so `false` used to pass an `isinstance(x, int)`
     check and then compare equal to a real exit status of 0.

  2. A run that did not terminate normally must never be trusted, and
     must never be written into a baseline. `subprocess` reports a
     signalled process as a negative returncode; the old code compared
     that against `expected_exit_code` as if it were an exit status and
     hashed whatever partial bytes the dying process had left behind.

  3. `fixtures/` is generated by `make_fixtures.py` (repo convention:
     no generated tree is committed) and the generator is deterministic,
     so the tree is re-derived rather than trusted.

Stdlib only.
"""

import hashlib
import json
import os
import subprocess
import sys
import tempfile
import unittest

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import regress  # noqa: E402
import make_fixtures  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
REGRESS_PY = os.path.join(HERE, "regress.py")
MAKE_FIXTURES_PY = os.path.join(HERE, "make_fixtures.py")
FIXTURES_DIR = os.path.join(HERE, "fixtures")
PY = sys.executable or "python3"

POSIX_ONLY = unittest.skipUnless(os.name == "posix", "signal semantics are POSIX-specific")


def setUpModule():
    """`fixtures/` is generated, not committed -- the same convention as
    `bundle-verifier/`, `exit-harness/` and `tamper-runner/`, which all ship a
    `make_fixtures.py` and commit no generated tree. Build it on demand so the
    CLI-level tests below are runnable from a fresh clone."""
    if not os.path.isdir(FIXTURES_DIR):
        import make_fixtures
        make_fixtures.build(FIXTURES_DIR)



def run_cli(args, cwd=None):
    proc = subprocess.run(
        [PY, REGRESS_PY] + args,
        cwd=cwd,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        timeout=120,
    )
    return proc.returncode, proc.stdout.decode("utf-8"), proc.stderr.decode("utf-8")


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)


def read_json(path):
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)


def read_text(path):
    with open(path, encoding="utf-8") as fh:
        return fh.read()


def write_baselines(root, tools):
    path = os.path.join(root, "baselines.json")
    write(path, json.dumps({"tools": tools}))
    return path


# A tool that writes part of a report, flushes it to disk, then kills itself
# with SIGKILL. The report file therefore exists and is non-empty, but is
# truncated -- the exact shape the old code hashed and trusted.
PARTIAL_THEN_KILL = '''\
import os, signal, sys
out = sys.argv[sys.argv.index("-o") + 1]
fh = open(out, "w", encoding="utf-8", newline="\\n")
fh.write('{"tool":"crasher","partial":tr')
fh.flush()
os.fsync(fh.fileno())
os.kill(os.getpid(), signal.SIGKILL)
'''

# Creates the report file, writes nothing, exits 0.
EMPTY_REPORT = '''\
import sys
out = sys.argv[sys.argv.index("-o") + 1]
open(out, "w", encoding="utf-8").close()
sys.exit(0)
'''

GOOD_REPORT = '''\
import sys
out = sys.argv[sys.argv.index("-o") + 1]
with open(out, "w", encoding="utf-8", newline="\\n") as fh:
    fh.write('{"tool":"good"}\\n')
sys.exit(0)
'''


class TempRootMixin:
    def make_root(self):
        td = tempfile.TemporaryDirectory()
        self.addCleanup(td.cleanup)
        return td.name

    def make_tool(self, root, name, source):
        write(os.path.join(root, name, "tool.py"), source)
        return os.path.join(root, name)


# ---------------------------------------------------------------------------
# 1. Booleans are not exit codes
# ---------------------------------------------------------------------------

class TestIsExitCode(unittest.TestCase):
    def test_real_ints_accepted(self):
        for value in (0, 1, 2, 127, -1, 255):
            self.assertTrue(regress.is_exit_code(value), value)

    def test_booleans_rejected(self):
        self.assertFalse(regress.is_exit_code(True))
        self.assertFalse(regress.is_exit_code(False))

    def test_non_ints_rejected(self):
        for value in ("0", 0.0, None, [], {}, object()):
            self.assertFalse(regress.is_exit_code(value), repr(value))

    def test_bool_would_have_compared_equal_to_zero(self):
        # The reason the bug was silent rather than loud.
        self.assertTrue(0 == False)  # noqa: E712
        self.assertTrue(1 == True)  # noqa: E712
        self.assertTrue(isinstance(False, int))


class TestBooleanExitCodeRejected(TempRootMixin, unittest.TestCase):
    def entry(self, exit_code):
        return {"command": ["python3", "tool.py"], "report_mode": "stdout",
                "expected_exit_code": exit_code}

    def test_false_rejected_by_load_baselines(self):
        path = write_baselines(self.make_root(), {"t1": self.entry(False)})
        with self.assertRaises(regress.SetupError):
            regress.load_baselines(path)

    def test_true_rejected_by_load_baselines(self):
        path = write_baselines(self.make_root(), {"t1": self.entry(True)})
        with self.assertRaises(regress.SetupError):
            regress.load_baselines(path)

    def test_zero_still_accepted(self):
        path = write_baselines(self.make_root(), {"t1": self.entry(0)})
        self.assertEqual(regress.load_baselines(path)["t1"]["expected_exit_code"], 0)

    def test_error_message_names_the_boolean(self):
        path = write_baselines(self.make_root(), {"t1": self.entry(False)})
        with self.assertRaises(regress.SetupError) as ctx:
            regress.load_baselines(path)
        self.assertIn("boolean", str(ctx.exception).lower())
        self.assertIn("t1", str(ctx.exception))

    def test_cli_exits_two_and_reports_error(self):
        root = self.make_root()
        self.make_tool(root, "t1", GOOD_REPORT)
        path = write_baselines(root, {"t1": self.entry(False)})
        code, out, _ = run_cli(["--root", root, "--baselines", path])
        self.assertEqual(code, 2)
        self.assertEqual(json.loads(out)["status"], "error")

    def test_a_tool_exiting_zero_no_longer_matches_false(self):
        # End-to-end statement of the defect: before the fix this baseline
        # was accepted and the tool was reported clean against `false`.
        root = self.make_root()
        self.make_tool(root, "t1", GOOD_REPORT)
        path = write_baselines(root, {"t1": {
            "command": ["python3", "tool.py", "-o", "{REPORT}"],
            "report_mode": "file",
            "expected_exit_code": False,
            "expected_report_sha256": None,
        }})
        code, out, _ = run_cli(["--root", root, "--baselines", path])
        self.assertEqual(code, 2, msg=out)

    def test_update_baselines_refuses_boolean_entry(self):
        root = self.make_root()
        self.make_tool(root, "t1", GOOD_REPORT)
        path = write_baselines(root, {"t1": {
            "command": ["python3", "tool.py", "-o", "{REPORT}"],
            "report_mode": "file",
            "expected_exit_code": False,
            "expected_report_sha256": None,
        }})
        code, _, err = run_cli(["--update-baselines", "--root", root, "--baselines", path])
        self.assertEqual(code, 2)
        self.assertIn("FAILED", err)
        # and the boolean was not quietly rewritten into a 0
        self.assertIs(read_json(path)["tools"]["t1"]["expected_exit_code"], False)


