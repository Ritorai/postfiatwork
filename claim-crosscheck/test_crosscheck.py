"""test_crosscheck.py -- tests for crosscheck.py.

Standard library only (unittest). Run with:

    python3 -m unittest test_crosscheck -v

Fixtures live under fixtures/, generated by make_fixtures.py (see that
file's docstring for why fixture bytes are embedded as base64 rather than
committed as loose files). A handful of tests also read directly from the
copy of this repository claim-crosscheck ships inside (../env-leak-scanner)
to pin the specific, confirmed contradiction the task brief names -- those
tests are grouped in RealRepoContradictionTests and are the only tests in
this file that reach outside claim-crosscheck/.
"""

import io
import json
import os
import subprocess
import sys
import tempfile
import unittest
from contextlib import redirect_stdout, redirect_stderr

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import crosscheck as cc  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
FIXTURES = os.path.join(HERE, "fixtures")
REPO_ROOT = os.path.dirname(HERE)


def fx(*parts):
    return os.path.join(FIXTURES, *parts)


def require_full_repo(testcase):
    """Skip a test that needs sibling tool directories (env-leak-scanner
    etc.) alongside claim-crosscheck -- true when running inside the full
    repository checkout, false for a standalone copy of just this
    directory (e.g. the clean tree shipped separately from the repo)."""
    if not os.path.isdir(os.path.join(REPO_ROOT, "env-leak-scanner")):
        testcase.skipTest(
            "requires the full repository checkout (env-leak-scanner not "
            "found next to claim-crosscheck); this is expected when "
            "running a standalone copy of just this tool directory")


def run_cli(argv):
    """Invoke crosscheck.main() in-process, capturing stdout/stderr."""
    out, err = io.StringIO(), io.StringIO()
    with redirect_stdout(out), redirect_stderr(err):
        rc = cc.main(argv)
    return rc, out.getvalue(), err.getvalue()


