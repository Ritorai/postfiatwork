class FindFileMatchesTests(unittest.TestCase):
    def setUp(self):
        self.report = {
            "confirmed_leaks": [
                {"file": "a.py", "line": 1, "category": "hostname"},
            ],
            "reviewed_benign": [
                {"file": "b.py", "line": 2, "category": "hostname"},
            ],
        }
        self.polarity = cc.classify_buckets(self.report)

    def test_finds_positive_match(self):
        matches = cc.find_file_matches(self.report, self.polarity, "a.py")
        self.assertEqual(len(matches), 1)
        self.assertEqual(matches[0].polarity, "positive")

    def test_finds_negative_match(self):
        matches = cc.find_file_matches(self.report, self.polarity, "b.py")
        self.assertEqual(len(matches), 1)
        self.assertEqual(matches[0].polarity, "negative")

    def test_no_match_returns_empty(self):
        matches = cc.find_file_matches(self.report, self.polarity, "c.py")
        self.assertEqual(matches, [])

    def test_pointer_parts_correct(self):
        matches = cc.find_file_matches(self.report, self.polarity, "a.py")
        self.assertEqual(matches[0].pointer_parts, ["confirmed_leaks", 0])

    def test_deterministic_bucket_order(self):
        # buckets iterated alphabetically regardless of dict insertion order
        report2 = {}
        report2["reviewed_benign"] = self.report["reviewed_benign"]
        report2["confirmed_leaks"] = self.report["confirmed_leaks"]
        polarity2 = cc.classify_buckets(report2)
        matches1 = cc.find_file_matches(self.report, self.polarity, "a.py")
        matches2 = cc.find_file_matches(report2, polarity2, "a.py")
        self.assertEqual(matches1[0].pointer_parts, matches2[0].pointer_parts)


