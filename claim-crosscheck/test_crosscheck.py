class RealRepoContradictionTests(unittest.TestCase):
    """Pins the exact contradiction named in the task brief: the README
    claims snapshot-diff/README.md carries a confirmed hostname leak; the
    committed report only has it in reviewed_benign."""

    @classmethod
    def setUpClass(cls):
        cls.readme_path = os.path.join(REPO_ROOT, "env-leak-scanner", "README.md")
        cls.report_path = os.path.join(REPO_ROOT, "env-leak-scanner",
                                        "leak_report_2026-08-04.json")
        if not os.path.isfile(cls.readme_path) or not os.path.isfile(
                cls.report_path):
            raise unittest.SkipTest(
                "env-leak-scanner sources not found next to claim-crosscheck")
        cls.result = cc.run_target(cls.readme_path, cls.report_path)

    def test_no_setup_error(self):
        self.assertIsNone(self.result.error)

    def test_exactly_one_discrepancy(self):
        self.assertEqual(len(self.result.discrepancies), 1)

    def test_discrepancy_is_snapshot_diff_presence(self):
        d = self.result.discrepancies[0]
        self.assertEqual(d["kind"], "PRESENCE")
        self.assertEqual(d["claim_detail"]["token"], "snapshot-diff/README.md")

    def test_readme_quote_matches_source_line_93(self):
        d = self.result.discrepancies[0]
        self.assertEqual(d["readme_line"], 93)
        text = cc.read_text_exact(self.readme_path)
        lines = text.split("\n")
        # line 93 (1-indexed) contains the start of the quote, though the
        # quote itself begins mid-line, right after "...at a time. ".
        self.assertIn("`LIMITATIONS.md`, `REVIEWERS_GUIDE.md`,", lines[92])
        self.assertIn(d["readme_quote"], text)
        idx = text.index(d["readme_quote"])
        self.assertEqual(cc.line_of(text, idx), 93)

    def test_json_pointer_resolves_to_benign_entry(self):
        d = self.result.discrepancies[0]
        report = cc.load_report(self.report_path)
        entry = cc.resolve_pointer(report, d["json_pointer"])
        self.assertEqual(entry["file"], "snapshot-diff/README.md")
        self.assertEqual(entry["verdict"], "benign")

    def test_json_pointer_is_reviewed_benign_bucket(self):
        d = self.result.discrepancies[0]
        self.assertTrue(d["json_pointer"].startswith("/reviewed_benign/"))

    def test_report_excerpt_matches_pointer_target(self):
        d = self.result.discrepancies[0]
        report = cc.load_report(self.report_path)
        entry = cc.resolve_pointer(report, d["json_pointer"])
        self.assertEqual(d["report_excerpt"], cc.excerpt_for_entry(entry))

    def test_confirmed_leaks_has_zero_entries_for_that_file(self):
        report = cc.load_report(self.report_path)
        matches = [e for e in report["confirmed_leaks"]
                   if e.get("file") == "snapshot-diff/README.md"]
        self.assertEqual(matches, [])

    def test_other_four_listed_files_all_confirmed(self):
        # LIMITATIONS.md, REVIEWERS_GUIDE.md, doc-validator/, bundle-index/
        # are the other four subjects of the same sentence -- all TRUE
        # claims, must NOT appear as discrepancies.
        tokens = {d["claim_detail"].get("token")
                  for d in self.result.discrepancies}
        for should_be_true in ("LIMITATIONS.md", "REVIEWERS_GUIDE.md",
                                "doc-validator/", "bundle-index/"):
            self.assertNotIn(should_be_true, tokens)

    def test_exit_code_is_1(self):
        self.assertEqual(cc.overall_exit_code([self.result]), 1)

    def test_fourteen_other_claims_matched(self):
        self.assertEqual(self.result.claims_checked, 15)
        self.assertEqual(len(self.result.discrepancies), 1)


