class JsonPointerTests(unittest.TestCase):
    def test_empty_parts_is_root_pointer(self):
        self.assertEqual(cc.make_pointer([]), "")

    def test_simple_pointer(self):
        self.assertEqual(cc.make_pointer(["confirmed_leaks", 3]), "/confirmed_leaks/3")

    def test_escapes_tilde(self):
        self.assertEqual(cc.pointer_escape("a~b"), "a~0b")

    def test_escapes_slash(self):
        self.assertEqual(cc.pointer_escape("a/b"), "a~1b")

    def test_escapes_both_in_pointer(self):
        pointer = cc.make_pointer(["weird~key/name", 0])
        self.assertEqual(pointer, "/weird~0key~1name/0")

    def test_integer_index_not_escaped(self):
        pointer = cc.make_pointer(["bucket", 12])
        self.assertTrue(pointer.endswith("/12"))

    def test_resolve_pointer_root(self):
        data = {"a": 1}
        self.assertIs(cc.resolve_pointer(data, ""), data)

    def test_resolve_pointer_nested(self):
        data = {"a": [{"b": 5}]}
        self.assertEqual(cc.resolve_pointer(data, "/a/0/b"), 5)

    def test_resolve_pointer_roundtrip_with_escaping(self):
        data = {"weird~key/name": [1, 2, 3]}
        pointer = cc.make_pointer(["weird~key/name", 2])
        self.assertEqual(cc.resolve_pointer(data, pointer), 3)

    def test_resolve_pointer_missing_key_raises(self):
        with self.assertRaises(KeyError):
            cc.resolve_pointer({"a": 1}, "/b")

    def test_resolve_pointer_invalid_no_leading_slash(self):
        with self.assertRaises(ValueError):
            cc.resolve_pointer({"a": 1}, "a")


class IterTreeTests(unittest.TestCase):
    def test_yields_root_first(self):
        data = {"a": 1}
        first = next(cc.iter_tree(data))
        self.assertEqual(first, ([], data))

    def test_dict_keys_sorted(self):
        data = {"z": 1, "a": 2}
        parts_seen = [p for p, _ in cc.iter_tree(data)]
        self.assertEqual(parts_seen, [[], ["a"], ["z"]])

    def test_list_indices_in_order(self):
        data = [10, 20, 30]
        parts_seen = [p for p, v in cc.iter_tree(data) if p]
        self.assertEqual(parts_seen, [[0], [1], [2]])

    def test_deterministic_across_dict_construction_order(self):
        d1, d2 = {}, {}
        d1["b"] = 1
        d1["a"] = 2
        d2["a"] = 2
        d2["b"] = 1
        self.assertEqual(list(cc.iter_tree(d1)), list(cc.iter_tree(d2)))


