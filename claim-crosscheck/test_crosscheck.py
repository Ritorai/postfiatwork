class CanonicalJsonTests(unittest.TestCase):
    def test_sorts_keys(self):
        text = cc.canonical_json({"b": 1, "a": 2})
        self.assertEqual(text, '{"a":2,"b":1}\n')

    def test_compact_separators(self):
        text = cc.canonical_json({"a": [1, 2], "b": {"c": 3}})
        self.assertNotIn(", ", text)
        self.assertNotIn(": ", text)

    def test_trailing_newline(self):
        self.assertTrue(cc.canonical_json({}).endswith("\n"))
        self.assertEqual(cc.canonical_json({}).count("\n"), 1)

    def test_ensure_ascii_escapes_unicode(self):
        text = cc.canonical_json({"x": "café"})
        self.assertIn("\\u00e9", text)
        self.assertNotIn("é", text)

    def test_key_order_independent_of_insertion_order(self):
        d1 = {}
        d1["z"] = 1
        d1["a"] = 2
        d2 = {}
        d2["a"] = 2
        d2["z"] = 1
        self.assertEqual(cc.canonical_json(d1), cc.canonical_json(d2))

    def test_nested_list_of_dicts_sorted(self):
        text = cc.canonical_json({"items": [{"b": 1, "a": 2}]})
        self.assertEqual(text, '{"items":[{"a":2,"b":1}]}\n')


