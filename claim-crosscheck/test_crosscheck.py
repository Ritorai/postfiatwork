    def test_ignores_three_column_rules_table(self):
        text = ("| Category | Rules | Example |\n|---|---|---|\n"
                 "| `hostname` | EL-HOST | x |\n")
        claims = cc.extract_table_count_claims(text, "R.md")
        self.assertEqual(claims, [])

    def test_zero_count_extracted(self):
        text = "| Category | Confirmed |\n|---|---|\n| `username` | 0 |\n"
        claims = cc.extract_table_count_claims(text, "R.md")
        self.assertEqual(claims[0].extra["expected"], 0)

