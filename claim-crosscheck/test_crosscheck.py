class MaskFencedBlocksTests(unittest.TestCase):
    def test_preserves_length(self):
        text = "before\n```\ncode 999 confirmed\n```\nafter"
        masked = cc.mask_fenced_blocks(text)
        self.assertEqual(len(masked), len(text))

    def test_preserves_newlines(self):
        text = "a\n```\nb\nc\n```\nd"
        masked = cc.mask_fenced_blocks(text)
        self.assertEqual(masked.count("\n"), text.count("\n"))

    def test_blanks_fence_interior(self):
        text = "```\n999 confirmed leaks\n```"
        masked = cc.mask_fenced_blocks(text)
        self.assertNotIn("999", masked)

    def test_leaves_outside_content_untouched(self):
        text = "121 confirmed leaks\n```\n999 confirmed leaks\n```"
        masked = cc.mask_fenced_blocks(text)
        self.assertTrue(masked.startswith("121 confirmed leaks\n"))

    def test_no_fence_unchanged(self):
        text = "no fences here at all"
        self.assertEqual(cc.mask_fenced_blocks(text), text)

    def test_unterminated_fence_left_unmasked(self):
        text = "before\n```\nunterminated 999 confirmed"
        masked = cc.mask_fenced_blocks(text)
        self.assertIn("999", masked)

    def test_multiple_fences_both_masked(self):
        text = "```\n1 confirmed\n```\ntext\n```\n2 confirmed\n```"
        masked = cc.mask_fenced_blocks(text)
        self.assertNotIn("1 confirmed", masked)
        self.assertNotIn("2 confirmed", masked)
        self.assertIn("text", masked)


