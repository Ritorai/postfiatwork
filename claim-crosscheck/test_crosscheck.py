class ExtractSummaryCountTests(unittest.TestCase):
    def test_confirmed_leaks_singular_and_plural(self):
        for phrase, n in [("1 confirmed leak", 1), ("121 confirmed leaks", 121)]:
            claims = cc.extract_summary_count_claims(phrase, "R.md")
            confirmed = [c for c in claims if c.extra.get("metric") == "confirmed"]
            self.assertEqual(len(confirmed), 1, phrase)
            self.assertEqual(confirmed[0].extra["expected"], n, phrase)

    def test_benign_phrase(self):
        text = "100 matches reviewed and dismissed as benign"
        claims = cc.extract_summary_count_claims(text, "R.md")
        self.assertEqual(len(claims), 1)
        self.assertEqual(claims[0].extra["metric"], "benign")
        self.assertEqual(claims[0].extra["expected"], 100)

    def test_stale_phrase(self):
        text = "0 stale review entries"
        claims = cc.extract_summary_count_claims(text, "R.md")
        metrics = {c.extra["metric"]: c.extra["expected"] for c in claims}
        self.assertEqual(metrics.get("stale"), 0)

    def test_stale_singular(self):
        text = "1 stale review entry"
        claims = cc.extract_summary_count_claims(text, "R.md")
        self.assertTrue(any(c.extra["metric"] == "stale" for c in claims))

    def test_across_files_phrase(self):
        text = "across 23 files"
        claims = cc.extract_summary_count_claims(text, "R.md")
        distinct = [c for c in claims if c.kind == "DISTINCT_FILE_COUNT"]
        self.assertEqual(len(distinct), 1)
        self.assertEqual(distinct[0].extra["expected"], 23)

    def test_across_one_file_singular(self):
        text = "across 1 file"
